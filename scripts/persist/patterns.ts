import { readFileSync, writeFileSync } from "node:fs";

// A review sheet of the exercise grouping: every catalogued exercise under its movement pattern.
interface Entry { id: string; name: string; pattern: string | null; equipment: string[]; unilateral: boolean; uses: number }
const cat: { entries: Entry[] } = JSON.parse(readFileSync("data/catalog/exercises.json", "utf8"));
const excluded: { name: string; uses: number; reason: string }[] = JSON.parse(readFileSync("data/reports/unmapped_exercises.json", "utf8")).filter((x: { id: string | null }) => !x.id);

const by = new Map<string, Entry[]>();
for (const e of cat.entries) (by.get(e.pattern ?? "(none)") ?? by.set(e.pattern ?? "(none)", []).get(e.pattern ?? "(none)")!).push(e);
const total = cat.entries.reduce((n, e) => n + e.uses, 0);

const lines = [
  "# Exercise grouping review sheet",
  "",
  `Generated by \`npm run persist:patterns\`. ${cat.entries.length} exercises in ${by.size} patterns, ${total} uses in the program. Within each pattern exercises are ordered by how often the program uses them; the number is the use count. Equipment in brackets (empty means bodyweight or none).`,
  "",
  "To change a grouping, add the exercise id to `data/catalog/overrides.json` (`{\"pattern\": \"...\"}`) or change the rule in `src/persist/classify.ts`, then run `npm run persist:all`. How to review: read each list and look for an exercise that does not belong; the first 15 in each list cover most of the use.",
  "",
];
for (const [pattern, list] of [...by].sort((a, b) => b[1].reduce((n, e) => n + e.uses, 0) - a[1].reduce((n, e) => n + e.uses, 0))) {
  const uses = list.reduce((n, e) => n + e.uses, 0);
  lines.push(`## ${pattern} (${list.length} exercises, ${uses} uses)`, "");
  lines.push(list.sort((a, b) => b.uses - a.uses || a.name.localeCompare(b.name)).map((e) => `${e.name} ${e.uses}${e.equipment.length ? ` [${e.equipment.join(", ")}]` : ""}`).join("; "), "");
}
lines.push(`## Kept out of the catalog (${excluded.length} names, ${excluded.reduce((n, x) => n + x.uses, 0)} uses)`, "", "Headings, instructions and fragments the parser read as items. They have no exercise and no pattern.", "");
lines.push(excluded.slice(0, 60).map((x) => `${x.name} ${x.uses} (${x.reason})`).join("; "), "");
writeFileSync("data/reports/patterns.md", lines.join("\n"));
console.log(`wrote data/reports/patterns.md: ${cat.entries.length} exercises, ${by.size} patterns`);
