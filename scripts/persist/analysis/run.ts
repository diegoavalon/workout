import { readFileSync, writeFileSync } from "node:fs";
import { buildRules } from "./rules.ts";
import { loadSlots, openDb, runSqlFiles } from "./lib.ts";
import * as q01 from "./q01-skeleton.ts";
import * as q02 from "./q02-slot-fill.ts";
import * as q03 from "./q03-rotation.ts";
import * as q04 from "./q04-progression.ts";
import * as q05 from "./q05-recycled.ts";
import * as q06 from "./q06-derivation.ts";
import * as q07 from "./q07-pairings.ts";
import * as q08 from "./q08-conditioning.ts";
import * as q09 from "./q09-volume.ts";
import { blockTemplate, progression, trackDerivation } from "./design.ts";
import { writeFileSync as wf } from "node:fs";

const db = openDb();
const slots = loadSlots(db);
const sql = runSqlFiles(db);
const parts: string[] = [];
const r1 = q01.run(slots);
parts.push(r1.md);
const r2 = q02.run(slots);
parts.push(r2.md);
const r3 = q03.run(slots);
parts.push(r3.md);
const r4 = q04.run(slots);
parts.push(r4.md);
const r5 = q05.run(slots);
parts.push(r5.md);
const r6 = q06.run(slots);
parts.push(r6.md);
const r7 = q07.run(sql);
parts.push(r7.md);
const r8 = q08.run(sql);
parts.push(r8.md);
const r9 = q09.run(slots);
parts.push(r9.md);
wf("data/design/block-template.json", JSON.stringify(blockTemplate(slots), null, 1));
wf("data/design/progression.json", JSON.stringify(progression(slots, r4.stats), null, 1));
wf("data/design/track-derivation.json", JSON.stringify(trackDerivation(r6.blockMaps, r6.csvSummary), null, 1));
const rep = JSON.parse(readFileSync("data/reports/build-report.json", "utf8"));
const cat = JSON.parse(readFileSync("data/catalog/exercises.json", "utf8"));
const totalUses = cat.entries.reduce((n: number, e: any) => n + e.uses, 0);
const unresolvedUses = cat.entries.filter((e: any) => !e.pattern).reduce((n: number, e: any) => n + e.uses, 0);
const rules = buildRules(slots, { q01: r1, q02: r2, q03: r3, q04: r4, q05: r5, q06: r6, q07: r7, q08: r8, q09: r9 }, { topUnresolved: [], excluded: JSON.parse(readFileSync("data/reports/unmapped_exercises.json", "utf8")).filter((x: any) => !x.id).length, excludedUses: JSON.parse(readFileSync("data/reports/unmapped_exercises.json", "utf8")).filter((x: any) => !x.id).reduce((n: number, x: any) => n + x.uses, 0), weeksObserved: rep.weeks.observed, weeksMissing: rep.weeks.missing, blocks: rep.blocks.length, unresolvedUses, totalUses });
const rulesMd = ["## Rules a generator could follow", "", "Each rule is a pattern the data supports, with how often it held and where it did not.", "", ...rules.flatMap((x, i) => [`### ${i + 1}. ${x.title}`, "", x.rule, "", `- **Evidence:** ${x.evidence}`, `- **Exceptions:** ${x.exceptions}`, ""])].join("\n");
const header = ["# Persist program analysis", "", `Generated by \`npm run persist:analyze\` from the seeded database: ${rep.weeks.observed} observed weeks (${rep.weeks.missing} missing) in ${rep.blocks.length} blocks, 8 tracks. Supporting CSV and JSON are in \`data/reports/analysis/\`; the draft design model is in \`data/design/\`. Where a table says "unresolved", the exercise has no pattern yet (see \`data/reports/unmapped_exercises.json\`).`, ""].join("\n");
writeFileSync("data/reports/analysis.md", [header, ...parts, rulesMd].join("\n\n") + "\n");
writeFileSync("data/reports/analysis/rules.json", JSON.stringify(rules, null, 1));

