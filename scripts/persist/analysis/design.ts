import { mkdirSync, writeFileSync } from "node:fs";
import type { Slot } from "./lib.ts";
import { schemes } from "./q04-progression.ts";

const OUT = "data/design";
mkdirSync(OUT, { recursive: true });
const write = (name: string, v: unknown) => writeFileSync(`${OUT}/${name}`, JSON.stringify(v, null, 1));

const mode = <T>(xs: T[]): T | undefined => {
  const c = new Map<string, { v: T; n: number }>();
  for (const x of xs) { const k = JSON.stringify(x); const e = c.get(k) ?? { v: x, n: 0 }; e.n++; c.set(k, e); }
  return [...c.values()].sort((a, b) => b.n - a.n)[0]?.v;
};
const share = <T>(xs: T[], v: T) => (xs.length ? +(xs.filter((x) => JSON.stringify(x) === JSON.stringify(v)).length / xs.length).toFixed(3) : 0);

const TRACK_IDS = ["pump-lift-5x", "pump-lift-4x", "pump-lift-3x", "pump-condition-5x", "pump-condition-4x", "pump-condition-3x", "perform", "minimalist"];

/** block-template.json: the skeleton as slots per day, with the exercise pool observed for each slot. */
export function blockTemplate(slots: Slot[]) {
  const tracks: Record<string, unknown> = {};
  for (const t of TRACK_IDS) {
    const ts = slots.filter((s) => s.track === t);
    const days: Record<string, unknown> = {};
    for (const d of [...new Set(ts.map((s) => s.day))].sort()) {
      const ds = ts.filter((s) => s.day === d);
      const type = mode(ds.map((s) => s.sessionType))!;
      const sameType = ds.filter((s) => s.sessionType === type);
      const skeleton = mode(sameType.map((s) => s.sections.map((x) => x.role)))!;
      const matching = sameType.filter((s) => JSON.stringify(s.sections.map((x) => x.role)) === JSON.stringify(skeleton));
      const roleSlots = skeleton.map((role, i) => {
        const secs = matching.map((s) => s.sections[i]);
        const pool = new Map<string, { exerciseId: string; name: string; pattern: string | null; n: number }>();
        for (const sec of secs) for (const it of sec.items.slice(0, role.startsWith("strength-intensity") ? 1 : 3)) if (it.exId) {
          const e = pool.get(it.exId) ?? { exerciseId: it.exId, name: it.exName!, pattern: it.pattern, n: 0 };
          e.n++;
          pool.set(it.exId, e);
        }
        const patterns = new Map<string, number>();
        for (const sec of secs) { const p = sec.items[0]?.pattern; if (p) patterns.set(p, (patterns.get(p) ?? 0) + 1); }
        return {
          role,
          format: mode(secs.map((x) => x.format)) ?? null,
          minutes: mode(secs.map((x) => [x.minutesMin, x.minutesMax])) ?? null,
          itemsPerSection: mode(secs.map((x) => x.items.length)) ?? 0,
          patternDistribution: Object.fromEntries([...patterns].sort((a, b) => b[1] - a[1])),
          exercisePool: ["warmup", "cooldown", "focus-note", "mobility", "active-recovery"].includes(role) ? undefined : [...pool.values()].sort((a, b) => b.n - a.n).slice(0, 40),
          observedSections: secs.length,
        };
      });
      days[d] = {
        type,
        typeShare: share(ds.map((s) => s.sessionType), type),
        skeleton: skeleton,
        skeletonShare: +(matching.length / (sameType.length || 1)).toFixed(3),
        weeksObserved: ds.length,
        slots: type === "note" ? [] : roleSlots,
      };
    }
    tracks[t] = { days };
  }
  return { note: "Generated by scripts/persist/analysis/design.ts from the seeded database. Pools list the exercises observed in each slot with counts of observed weeks.", tracks };
}

/** progression.json: working-set schemes by slot role and week, plus the rules measured in q04. */
export function progression(slots: Slot[], stats: any) {
  const all = schemes(slots);
  const out: Record<string, unknown> = {};
  for (const family of ["pump-lift", "pump-condition", "perform", "minimalist"]) {
    const fam = all.filter((x) => x.track.startsWith(family));
    const roles: Record<string, unknown> = {};
    for (const role of ["strength-intensity-1", "strength-intensity-2"]) {
      const rs = fam.filter((x) => x.role === role);
      if (!rs.length) continue;
      const byWeek: Record<string, unknown> = {};
      for (let w = 1; w <= 6; w++) {
        const ws = rs.filter((x) => x.week === w);
        if (!ws.length) continue;
        const counts = new Map<string, number>();
        for (const x of ws) counts.set(`${x.reps}|${x.rpe}`, (counts.get(`${x.reps}|${x.rpe}`) ?? 0) + 1);
        byWeek[w] = {
          observed: ws.length,
          workingSetsMode: mode(ws.map((x) => x.workingSets)),
          tempoMode: mode(ws.map((x) => x.tempo)),
          restMode: mode(ws.map((x) => x.rest)),
          shapes: Object.fromEntries([...new Set(ws.map((x) => x.shape))].map((sh) => [sh, ws.filter((x) => x.shape === sh).length])),
          schemes: [...counts].sort((a, b) => b[1] - a[1]).slice(0, 6).map(([k, n]) => ({ reps: k.split("|")[0], rpe: k.split("|")[1], slots: n })),
        };
      }
      roles[role] = { observed: rs.length, byWeek };
    }
    out[family] = roles;
  }
  return {
    note: "Generated from the seeded database. 'reps' lists the reps of each working set in order; 'max' is a max-reps set. Rules measured over all strength-intensity-1 sequences are in data/reports/analysis.md section 4.",
    rules: (() => {
      const pc = (n: number, d: number) => `${((100 * n) / d).toFixed(0)}%`;
      const steps = new Map<number, number>(stats.stepDist);
      const total = [...steps.values()].reduce((x, y) => x + y, 0);
      const down = [...steps].filter(([d]) => d < 0).reduce((n, [, c]) => n + c, 0);
      return [
        `Working sets are ranked by RPE, usually starting 7/8/9 (${pc(stats.rpeStd, stats.rpeTot)} of weeks).`,
        `Within a block the working-set count is constant in ${pc(stats.setsFixed, stats.seqCount)} of slot sequences and at most two tempos are used in ${pc(stats.tempoFixed, stats.seqCount)}.`,
        `Opening reps fall between same-parity weeks (two weeks apart) in ${down} of ${total} steps, usually by one or two reps.`,
        `Odd and even weeks do not reliably form a heavy/light pair: opening reps separate cleanly by parity in ${pc(stats.splitConsistent, stats.splitTotal)} of slots, and the heavier parity is odd in ${stats.heavyCount.odd} and even in ${stats.heavyCount.even}.`,
      ];
    })(),
    families: out,
  };
}

export function trackDerivation(blockMaps: { derived: string; base: string; block: number; mappings: string[] }[], summary: Record<string, unknown>[]) {
  return {
    note: "No single rule derives the lower-frequency tracks. Same-day copies are common only for Pump Condition 5x and Perform (copy the Pump Lift 5x main lift on the same day number). Pump Lift 4x/3x and Pump Condition 4x/3x reuse Pump Lift 5x / Pump Condition 5x sessions but pick a different subset and order of days in each block, so a template is needed per block (the mapping below), not a global rule. Minimalist keeps the movement pattern but changes the lift.",
    relations: summary,
    perBlockMappings: blockMaps,
    mappingNotation: "'derived day = base day'; a trailing ~ means matched by pattern only; - means no match",
  };
}
